"""Builds a small RemixIcon font + CSS containing only the icons the site uses.

Run from the project root after adding or changing icons:
    pip install fonttools brotli
    python scripts/build-icon-subset.py

Output: src/styles/remixicon/remixicon-subset.css and remixicon-subset.woff2
To go back to the full icon set instead, in src/main.tsx replace
    import './styles/remixicon/remixicon-subset.css'
with
    import 'remixicon/fonts/remixicon.css'
"""
import glob
import os
import re
import sys

from fontTools import subset

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_CSS = os.path.join(ROOT, "node_modules", "remixicon", "fonts", "remixicon.css")
SRC_FONT = os.path.join(ROOT, "node_modules", "remixicon", "fonts", "remixicon.ttf")
OUT_DIR = os.path.join(ROOT, "src", "styles", "remixicon")

css = open(SRC_CSS, encoding="utf-8").read()
icons = dict(re.findall(r'\.ri-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)";\s*\}', css))

used = set()
for path in glob.glob(os.path.join(ROOT, "src", "**", "*.ts*"), recursive=True):
    text = open(path, encoding="utf-8").read()
    used.update(re.findall(r"\bri-([a-z0-9-]+)", text))
    # names written without the "ri-" prefix, e.g. { icon: "instagram-line" }
    used.update(s for s in re.findall(r'["\'`]([a-z0-9-]+)["\'`]', text) if s in icons)
used = sorted(n for n in used if n in icons)

missing_hint = sorted(
    n
    for path in glob.glob(os.path.join(ROOT, "src", "**", "*.ts*"), recursive=True)
    for n in re.findall(r"\bri-([a-z0-9]+(?:-[a-z0-9]+)*-(?:line|fill))\b", open(path, encoding="utf-8").read())
    if n not in icons
)
if missing_hint:
    print("Warning: these icon names do not exist in RemixIcon:", ", ".join(sorted(set(missing_hint))))

os.makedirs(OUT_DIR, exist_ok=True)
font_out = os.path.join(OUT_DIR, "remixicon-subset.woff2")
options = subset.Options()
options.flavor = "woff2"
options.layout_features = []
options.name_IDs = []
options.notdef_outline = True
font = subset.load_font(SRC_FONT, options)
subsetter = subset.Subsetter(options)
subsetter.populate(unicodes=[int(icons[n], 16) for n in used])
subsetter.subset(font)
subset.save_font(font, font_out, options)

rules = "\n".join(f'.ri-{n}:before {{ content: "\\{icons[n]}"; }}' for n in used)
out_css = f"""/* Generated by scripts/build-icon-subset.py — do not edit by hand. */
/* RemixIcon (Remix Icon License 1.0), subset to the {len(used)} icons used on this site. */
@font-face {{
  font-family: "remixicon";
  src: url("./remixicon-subset.woff2") format("woff2");
  font-display: swap;
}}

[class^="ri-"], [class*=" ri-"] {{
  font-family: 'remixicon' !important;
  font-style: normal;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}}

{rules}
"""
open(os.path.join(OUT_DIR, "remixicon-subset.css"), "w", encoding="utf-8").write(out_css)
print(f"{len(used)} icons -> {os.path.getsize(font_out) // 1024} KB woff2")
sys.exit(0)
